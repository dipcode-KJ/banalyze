CREATE TABLE teams (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  source_team_id VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  short_name VARCHAR(40) NOT NULL,
  division VARCHAR(16) NOT NULL,
  conference VARCHAR(32) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE games (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  source_game_id VARCHAR(64) NOT NULL UNIQUE,
  season VARCHAR(16) NOT NULL,
  game_date DATE NOT NULL,
  status VARCHAR(24) NOT NULL,
  home_team_id INT UNSIGNED NOT NULL,
  away_team_id INT UNSIGNED NOT NULL,
  home_score SMALLINT UNSIGNED NULL,
  away_score SMALLINT UNSIGNED NULL,
  venue VARCHAR(160) NULL,
  raw_payload JSON NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_games_date (game_date),
  INDEX idx_games_season (season),
  CONSTRAINT fk_games_home_team FOREIGN KEY (home_team_id) REFERENCES teams(id),
  CONSTRAINT fk_games_away_team FOREIGN KEY (away_team_id) REFERENCES teams(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE team_daily_records (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  team_id INT UNSIGNED NOT NULL,
  season VARCHAR(16) NOT NULL,
  record_date DATE NOT NULL,
  wins SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  losses SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  points_for INT NOT NULL DEFAULT 0,
  points_against INT NOT NULL DEFAULT 0,
  home_wins SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  home_losses SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  away_wins SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  away_losses SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uniq_team_daily (team_id, season, record_date),
  CONSTRAINT fk_records_team FOREIGN KEY (team_id) REFERENCES teams(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE team_advanced_stats (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  team_id INT UNSIGNED NOT NULL,
  season VARCHAR(16) NOT NULL,
  assists DECIMAL(8,2) NULL,
  turnovers DECIMAL(8,2) NULL,
  total_rebounds DECIMAL(8,2) NULL,
  three_point_makes DECIMAL(8,2) NULL,
  three_point_attempts DECIMAL(8,2) NULL,
  three_point_percentage DECIMAL(5,2) NULL,
  pace DECIMAL(8,2) NULL,
  offensive_rating DECIMAL(8,2) NULL,
  defensive_rating DECIMAL(8,2) NULL,
  source VARCHAR(160) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uniq_team_advanced (team_id, season),
  INDEX idx_team_advanced_season (season),
  CONSTRAINT fk_advanced_team FOREIGN KEY (team_id) REFERENCES teams(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE national_team_games (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  source_game_id VARCHAR(96) NOT NULL UNIQUE,
  source_provider VARCHAR(32) NOT NULL DEFAULT 'JBA',
  source_url VARCHAR(500) NOT NULL,
  competition VARCHAR(180) NOT NULL,
  game_date DATE NOT NULL,
  tipoff_time TIME NULL,
  status VARCHAR(40) NOT NULL,
  venue VARCHAR(180) NULL,
  home_team VARCHAR(120) NOT NULL,
  away_team VARCHAR(120) NOT NULL,
  home_score SMALLINT UNSIGNED NULL,
  away_score SMALLINT UNSIGNED NULL,
  japan_side ENUM('home', 'away') NOT NULL,
  period_scores JSON NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_national_games_date (game_date),
  INDEX idx_national_games_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE national_team_box_scores (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  game_id INT UNSIGNED NOT NULL,
  team_name VARCHAR(120) NOT NULL,
  is_japan TINYINT(1) NOT NULL DEFAULT 0,
  points SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  three_point_makes SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  three_point_attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  two_point_makes SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  two_point_attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  free_throw_makes SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  free_throw_attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  fouls SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  offensive_rebounds SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  defensive_rebounds SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  total_rebounds SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  turnovers SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  assists SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  steals SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  blocks SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uniq_national_box_team (game_id, team_name),
  INDEX idx_national_box_japan (is_japan),
  CONSTRAINT fk_national_box_game FOREIGN KEY (game_id) REFERENCES national_team_games(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE national_team_player_stats (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  game_id INT UNSIGNED NOT NULL,
  team_name VARCHAR(120) NOT NULL,
  is_japan TINYINT(1) NOT NULL DEFAULT 0,
  player_number VARCHAR(12) NOT NULL,
  player_name VARCHAR(120) NOT NULL,
  starter TINYINT(1) NOT NULL DEFAULT 0,
  points SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  three_point_makes SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  three_point_attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  two_point_makes SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  two_point_attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  free_throw_makes SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  free_throw_attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  fouls SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  offensive_rebounds SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  defensive_rebounds SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  total_rebounds SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  turnovers SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  assists SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  steals SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  blocks SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  minutes_seconds SMALLINT UNSIGNED NULL,
  did_not_play TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uniq_national_player (game_id, team_name, player_number, player_name),
  INDEX idx_national_player_japan (is_japan, player_name),
  CONSTRAINT fk_national_player_game FOREIGN KEY (game_id) REFERENCES national_team_games(id) ON DELETE CASCADE
